// One-off generator: pulls @PBExpTable straight out of the game's own
// 068_PBExperience script (inside Data/Scripts.rxdata) and writes lib/expTable.js.
// Re-run it if the game updates.  node tools/gen-expTable.js
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';
import { join } from 'node:path';
import { loadAll, strToJs } from '../src/marshal.js';

const GAME_DIR = process.argv[2] || process.env.PKMNZ_GAME_DIR;
if (!GAME_DIR) {
  console.error('usage: node tools/gen-expTable.js "<path to the Pokemon Z folder>"');
  process.exit(2);
}

const scripts = loadAll(new Uint8Array(readFileSync(join(GAME_DIR, 'Data/Scripts.rxdata'))))[0].value;

let src = null;
let name = null;
for (const entry of scripts.items) {
  const nm = strToJs(entry.items[1]);
  const code = inflateSync(Buffer.from(entry.items[2].bytes)).toString('utf8');
  if (/@PBExpTable\s*=\s*\[/.test(code)) { src = code; name = nm; break; }
}
if (!src) throw new Error('could not find @PBExpTable in Data/Scripts.rxdata');

const body = src.slice(src.indexOf('@PBExpTable=['));
const arr = body.slice(body.indexOf('[') + 1, body.indexOf(']'));
const nums = arr
  .split(/\r?\n/)
  .map((l) => l.replace(/#.*$/, ''))
  .join('')
  .split(',')
  .map((s) => s.trim())
  .filter((s) => s.length)
  .map(Number);

if (nums.some((n) => !Number.isFinite(n))) throw new Error('non-numeric entry in the table');
if (nums.length !== 6 * 101) throw new Error(`expected 606 entries, parsed ${nums.length}`);

const rows = [];
for (let g = 0; g < 6; g++) rows.push(nums.slice(g * 101, g * 101 + 101));

const GROWTH = ['Medium', 'Erratic', 'Fluctuating', 'Parabolic', 'Fast', 'Slow'];
const out = `// GENERATED by tools/gen-expTable.js from ${name} in Data/Scripts.rxdata.
// Total experience required to *be* at a given level, indexed [growthRate][level].
// Level 0 is -1 (unused); MAXIMUMLEVEL is 100 in this game's Settings.
export const MAXLEVEL = 100;
export const GROWTH_RATES = ${JSON.stringify(GROWTH)};
export const EXP_TABLE = [
${rows.map((r, i) => `  // ${GROWTH[i]}\n  [${r.join(',')}],`).join('\n')}
];

/** Total exp needed to be at \`level\` (mirrors PBExperience.pbGetStartExperience). */
export function startExperience(level, growth) {
  if (growth < 0 || growth > 5) throw new Error(\`invalid growth rate \${growth}\`);
  const l = Math.max(0, Math.min(level, MAXLEVEL));
  return EXP_TABLE[growth][l];
}

/** Level for a given exp total (mirrors PBExperience.pbGetLevelFromExperience). */
export function levelFromExperience(exp, growth) {
  const t = EXP_TABLE[growth];
  for (let i = 0; i <= MAXLEVEL; i++) {
    if (exp === t[i]) return i;
    if (exp < t[i]) return i - 1;
  }
  return MAXLEVEL;
}
`;

writeFileSync(new URL('../src/expTable.js', import.meta.url), out);
console.log(`wrote src/expTable.js from ${name}: 6 growth rates x 101 levels`);
console.log(`  Medium L100=${rows[0][100]}  Parabolic L2=${rows[3][2]}  Slow L100=${rows[5][100]}`);
